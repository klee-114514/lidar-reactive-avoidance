//=============================================================================
// encoder_decode.v  —— 编码器正交解码 + 测速（单路，一个轮子一份）
//-----------------------------------------------------------------------------
// 编码器是什么：
//   电机屁股后面装了个"带刻度的轮子"，轮子转的时候会吐出两路方波 A 相和 B 相。
//   转得越快，方波越密；转的方向不同，A、B 两路"谁先谁后"就反过来。
//   所以：数方波个数 = 知道走了多远；看谁先谁后 = 知道往哪走。
//
// 本模块做四件事：
//   1) 两级同步   —— 板外信号先进 FPGA，必须"打两拍"搬进自己的时钟域
//   2) 4 倍频解码 —— A、B 两相每次跳变都计一个数（比只数 A 相精细 4 倍）
//   3) 累计计数   —— count：从开机到现在的总计数，带正负
//   4) 定时测速   —— speed：每 SPEED_MS 毫秒"这一段时间差了多少个计数"
//                    也就是速度。以后 PID 就是拿这个值去跟目标值比。
//
// 单位约定：
//   count / speed 都是补码，正数 = 正转，负数 = 反转（和 duty_cmd 口径一致）
//   本模块故意不做 "cm/s" 换算 —— 那要用到轮径、编码器线数、减速比，
//   三个数里错一个就全盘错。原始计数值交给导航层去换算。
//=============================================================================
module encoder_decode #(
    parameter CLK_FREQ = 50_000_000,   // 输入时钟频率（Hz）
    parameter SPEED_MS = 5,            // 测速周期（毫秒）。PID 的控制周期就跟这个一致
    parameter INVERT   = 0             // 方向反了就把它改成 1，不用去重新焊线
)(
    input  wire        clk,
    input  wire        rst_n,
    input  wire        enc_a,          // 编码器 A 相
    input  wire        enc_b,          // 编码器 B 相
    output reg  [31:0] count,          // 累计计数（4 倍频），补码
    output reg  [15:0] speed,          // 每 SPEED_MS 的计数差，补码
    output reg         dir,            // 1 = 正转，0 = 反转
    output reg         speed_strobe    // 测速更新脉冲（高 1 个时钟）
);

    // 一个测速周期有多少个时钟：50MHz / 1000 × 5 = 250000
    localparam STROBE_CYC = CLK_FREQ / 1000 * SPEED_MS;

    // =========================================================================
    // 所有 reg / wire 集中声明在模块开头（ModelSim 不允许"先用后声明"）
    // =========================================================================
    reg  [1:0]  a_sync;      // A 相两级同步
    reg  [1:0]  b_sync;      // B 相两级同步
    reg  [1:0]  state_d;     // 上一拍的 (A,B)
    reg         up_flag;     // 本拍检测到"向正方向走了一步"
    reg         dn_flag;     // 本拍检测到"向负方向走了一步"
    reg  [15:0] acc;         // 本测速周期内累计的计数
    reg  [31:0] strobe_cnt;  // 测速用计数器
    wire [1:0]  state_q;     // 当前拍的 (A,B)
    wire [3:0]  trans;       // {上一拍, 当前拍}，共 4 位

    // -------------------------------------------------------------------------
    // 1) 两级同步（打两拍）
    //    编码器是板外信号，它跳变的时刻和你的时钟没有任何关系。
    //    直接拿它去计数，可能正好卡在跳变瞬间，导致计数随机出错（叫"亚稳态"）。
    //    解决办法：连过两个 D 触发器，第二级的输出就"稳定"了。
    // -------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            a_sync <= 2'b00;
            b_sync <= 2'b00;
            state_d <= 2'b00;
        end
        else begin
            a_sync  <= {a_sync[0], enc_a};   // 左移：新的从最低位进
            b_sync  <= {b_sync[0], enc_b};
            state_d <= state_q;              // 记下上一拍的 (A,B)
        end
    end

    assign state_q = {a_sync[1], b_sync[1]};   // 取打过两拍的那一级
    assign trans   = {state_d, state_q};

    // -------------------------------------------------------------------------
    // 2) 4 倍频正交解码
    //    (A,B) 这一对只会沿着一个圈转：
    //        正转： 00 → 10 → 11 → 01 → 00 ...
    //        反转： 00 → 01 → 11 → 10 → 00 ...
    //    顺着圈走就是正转（+1），倒着走就是反转（-1）。
    //    其它跳变（比如 00 → 11）说明漏采了或者有毛刺，直接当没发生，不计。
    // -------------------------------------------------------------------------
    always @(*) begin
        up_flag = 1'b0;
        dn_flag = 1'b0;
        case (trans)
            // 正转的 4 种合法跳变
            4'b0010, 4'b1011, 4'b1101, 4'b0100: up_flag = 1'b1;
            // 反转的 4 种合法跳变
            4'b0001, 4'b0111, 4'b1110, 4'b1000: dn_flag = 1'b1;
            default: ;                       // 没跳变 / 非法跳变
        endcase
    end

    // -------------------------------------------------------------------------
    // 3) 计数 + 累计 + 定时测速（全部放在同一个 always 块里）
    //    注意：一个 reg 只能被一个 always 块赋值，分成两块综合会报多驱动错误
    // -------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            count        <= 32'd0;
            acc          <= 16'd0;
            dir          <= 1'b0;
            strobe_cnt   <= 32'd0;
            speed        <= 16'd0;
            speed_strobe <= 1'b0;
        end
        else begin
            speed_strobe <= 1'b0;            // 默认拉低，只在到点的那一拍给高

            // ---- 3a) 计数 ----
            if (up_flag) begin
                count <= count + 32'd1;      // 累计计数 +1
                acc   <= acc + 16'd1;        // 本周期内 +1
                dir   <= (INVERT == 0) ? 1'b1 : 1'b0;
            end
            else if (dn_flag) begin
                count <= count - 32'd1;
                acc   <= acc - 16'd1;
                dir   <= (INVERT == 0) ? 1'b0 : 1'b1;
            end

            // ---- 3b) 定时测速：每 SPEED_MS 锁存一次，然后清零重新计 ----
            if (strobe_cnt >= STROBE_CYC - 1) begin
                strobe_cnt   <= 32'd0;
                speed        <= acc;         // acc 就是"这段时间差了多少个计数"= 速度
                acc          <= 16'd0;       // 清零，下一段重新数
                speed_strobe <= 1'b1;        // 给上层一个"数据新鲜"的脉冲
            end
            else begin
                strobe_cnt <= strobe_cnt + 32'd1;
            end
        end
    end

endmodule

//=============================================================================
// tb6612_driver.v  —— TB6612FNG 单路直流电机驱动（内含 PWM 生成）
//-----------------------------------------------------------------------------
// 作用：把一条"带符号的占空比指令"翻译成 TB6612 需要的 3 根线
//          AIN1 / AIN2 ：方向（两个普通数字电平）
//          PWMA        ：速度（一个 20kHz 的 PWM 方波）
//       并保证 pwm_enable 拉低时，所有输出立即断电（安全联锁）
//
// 一个电机例化一份，左右两轮就例化两次。
//
// 单位约定：
//   duty_cmd 是 16 位补码（2 的补码，最高位 = 1 表示负数）
//     正数 = 正转，负数 = 反转
//     绝对值 = 占空比千分比：0 = 停，1000 = 全速
//   例：16'd500  → 正转 50%
//       16'hFF0C = -500 → 反转 50%
//
// 为什么要"补码"而不是"方向位 + 数值"两个端口？
//   因为接口文档里已经冻结了补码口径，以后 PID 的输出可以直接接上来，不用改。
//=============================================================================
module tb6612_driver #(
    parameter CLK_FREQ = 50_000_000,   // 输入时钟频率（Hz），ACG720 板载 = 50M
    parameter PWM_FREQ = 20_000,       // PWM 频率（Hz）。建议 20k；别低于 10k（会啸叫），别超 100k（芯片发烫）
    parameter DUTY_MAX = 1000          // 占空比满量程（千分比），填 1000 表示"1000 = 全速"
)(
    input  wire        clk,            // 50MHz 主时钟
    input  wire        rst_n,          // 低电平复位（按键按下 = 0）
    input  wire        pwm_enable,     // 安全联锁：低 = 立即断电，主逻辑无权拉高
    input  wire        stop_mode,      // 指令为 0 时怎么停：1 = 短路刹车（停得稳），0 = 滑行（省电）
    input  wire [15:0] duty_cmd,       // 带符号占空比指令（补码）
    output reg         ain1,           // 方向线 1
    output reg         ain2,           // 方向线 2
    output reg         pwm             // 速度线（PWM 方波）
);

    // ---- PWM 一个周期有多少个时钟（50MHz / 20kHz = 2500） ----
    localparam PWM_PERIOD = CLK_FREQ / PWM_FREQ;

    // =========================================================================
    // 所有 reg / wire 集中声明在模块开头。
    // 不要写到一半再声明——ModelSim 会报 "Undefined variable"（教材 §6.2）
    // =========================================================================
    reg  [15:0] duty_abs;      // duty_cmd 的绝对值（恒为正）
    reg         dir_fwd;       // 1 = 正转，0 = 反转
    reg  [15:0] pwm_cnt;       // PWM 周期计数器：0 → PWM_PERIOD-1
    wire [15:0] duty_lim;      // 限幅之后的占空比（最大 DUTY_MAX）
    reg  [15:0] pwm_thr;       // 本周期的比较阈值（打一拍，见 §3）

    // -------------------------------------------------------------------------
    // 1) 拆方向：看最高位判断正负，再取绝对值
    //    为什么这么写：补码取绝对值 = 全部取反后加 1，是数字电路的固定套路
    //      例：-500 的补码是 16'hFE0C
    //          ~16'hFE0C = 16'h01F3，+1 = 16'h01F4 = 500  ✔
    // -------------------------------------------------------------------------
    always @(*) begin
        if (duty_cmd[15] == 1'b1) begin       // 最高位 = 符号位，1 表示负数
            dir_fwd  = 1'b0;                  // 负数 → 反转
            duty_abs = (~duty_cmd) + 16'd1;   // 补码取绝对值
        end
        else begin
            dir_fwd  = 1'b1;                  // 正数 → 正转
            duty_abs = duty_cmd;
        end
    end

    // -------------------------------------------------------------------------
    // 2) 限幅：不管上层给多大，最多按满速跑，防止溢出写崩
    // -------------------------------------------------------------------------
    assign duty_lim = (duty_abs > DUTY_MAX[15:0]) ? DUTY_MAX[15:0] : duty_abs;

    // -------------------------------------------------------------------------
    // 3) 千分比 → PWM 计数值阈值
    //      全速 1000 → 1000 × 2500 / 1000 = 2500 → 整个周期都是高电平
    //      半速  500 →  500 × 2500 / 1000 = 1250 → 半个周期高电平
    //
    //    ★2026-10-08 改（60K 器件上 setup 违例的元凶之一）★
    //      旧写法：
    //          assign duty_scaled = duty_lim * PWM_PERIOD;
    //          assign pwm_thr     = duty_scaled / DUTY_MAX;   // ← 【变量/除法】
    //      PnR 实测这条路径 34.99ns（50MHz 只有 20ns），而且它和
    //      "cur_n→段逻辑→目标速度→PID→duty" 串在同一拍里，
    //      在 GW5AT-60B 上直接呈负裕量（-15ns，312 个端点违例）。
    //      "除法是常数运算，综合器会自动化简成移位加法"这句话【不成立】。
    //
    //      现在：比例 PWM_PERIOD/DUTY_MAX 在综合期算成定点常数 THR_MUL/2^THR_SHIFT
    //      （2500/1000 → 2560/1024 = 2.5，误差 ≤ 1/1024 满量程，对 PWM 无意义），
    //      再用"常数乘 + 右移"实现；并且把结果【打一拍】，
    //      于是 duty → pwm 之间被切成两级组合逻辑，每级都远短于 20ns。
    // -------------------------------------------------------------------------
    localparam integer THR_SHIFT = 10;
    localparam integer THR_MUL   = (PWM_PERIOD << THR_SHIFT) / DUTY_MAX;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            pwm_thr <= 16'd0;
        else
            // ★注意位宽★：Verilog 里 a*b 的结果宽度 = max(两个操作数宽度)，
            //   写成 duty_lim * THR_MUL[15:0] 会被截成 16 位（250×2560 溢出成 50176>>10 = 49），
            //   必须把 THR_MUL 提升到 32 位上下文才是真乘。
            //   sim/tb_tb6612_duty.v 就是靠"数一个周期里 pwm 高了多少拍"抓到这个坑的。
            pwm_thr <= (duty_lim * THR_MUL[31:0]) >> THR_SHIFT;
    end

    // -------------------------------------------------------------------------
    // 4) PWM 计数器：0 → 2499 循环，数到 2499 回 0
    // -------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            pwm_cnt <= 16'd0;
        else if (!pwm_enable)                 // 断电时计数器也归零，重新使能时波形干净
            pwm_cnt <= 16'd0;
        else if (pwm_cnt >= PWM_PERIOD - 1)
            pwm_cnt <= 16'd0;
        else
            pwm_cnt <= pwm_cnt + 16'd1;
    end

    // -------------------------------------------------------------------------
    // 5) 输出逻辑：对照 TB6612 真值表
    //       AIN1=1 AIN2=0 PWM=1  → 正转
    //       AIN1=0 AIN2=1 PWM=1  → 反转
    //       AIN1=1 AIN2=1        → 短路刹车（电机两端被短接，停得干脆）
    //       AIN1=0 AIN2=0        → 停止 / 滑行（输出关断）
    // -------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            ain1 <= 1'b0;
            ain2 <= 1'b0;
            pwm  <= 1'b0;
        end
        else if (!pwm_enable) begin           // 安全联锁：立即断电，全部拉低
            ain1 <= 1'b0;
            ain2 <= 1'b0;
            pwm  <= 1'b0;
        end
        else if (duty_lim == 16'd0) begin     // 指令为 0 → 停
            if (stop_mode) begin              // 短路刹车
                // ⚠️ 2026-09-26 改：pwm 从 1'b1 变成 1'b0（安全保险，实测踩出来的）
                //
                //   TB6612 真值表里 IN1=IN2=1 就是短路刹车，【和 PWM 是什么无关】，
                //   所以这里把 pwm 拉高本来就是多余的。而多余的这个 1
                //   带来一个很恶劣的故障模式：
                //     万一有一根方向线断了（TB6612 那端悬空，读到 0），
                //     实际收到的就变成 1/0 + PWM=1 —— 那是【全速正转】！
                //     而 FPGA 这边还以为自己在刹车，状态机停在待机、
                //     永远不会主动停 → 上电就全速冲出去，停不下来（真事）。
                //   改成 0 之后：同样的断线变成 1/0 + PWM=0 = 仍然是短路刹车，
                //   电机安静地停住。刹车效果一点没减弱。
                ain1 <= 1'b1;
                ain2 <= 1'b1;
                pwm  <= 1'b0;
            end
            else begin                        // 滑行
                ain1 <= 1'b0;
                ain2 <= 1'b0;
                pwm  <= 1'b0;
            end
        end
        else if (dir_fwd) begin               // 正转
            ain1 <= 1'b1;
            ain2 <= 1'b0;
            pwm  <= (pwm_cnt < pwm_thr);      // 计数值小于阈值 → 输出高
        end
        else begin                            // 反转
            ain1 <= 1'b0;
            ain2 <= 1'b1;
            pwm  <= (pwm_cnt < pwm_thr);
        end
    end

endmodule

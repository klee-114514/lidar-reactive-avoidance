//=============================================================================
// motor_pid.v —— 单路速度闭环 PID（一个轮子一份）
//-----------------------------------------------------------------------------
// 它在整个系统里站的位置：
//
//     拨码/导航  ──target──┐
//                          ├──►【 motor_pid 】──duty──► tb6612_driver ──► 电机
//     编码器 ────actual───┘                                  │
//            ▲                                               │
//            └──────────────── 轮子真的转了 ◄─────────────────┘
//
//   这就是"闭环"：不是"我让你给 50% 占空比"（开环），
//   而是"我要 200 的速度，你自己看着办，低了就多给点，超了就少给点"。
//
// 为什么必须闭环（调车时你会亲眼看到）：
//   同样 30% 占空比，电量满时轮子转得快、电量低时转得慢；
//   左边轮子摩擦大、右边轮子摩擦小，同一个占空比两轮速度就不一样（车跑偏）。
//   开环控制这三个问题一个都解决不了 —— 闭环全自动搞定。
//
//=============================================================================
// 【先搞懂 PID 三项各管什么】（这一段比代码重要，调车时你会反复回来读）
//
//   P（比例）  ：误差 × KP = 出力。
//                误差大就使劲推，见效快。**只看现在**。
//   I（积分）  ：把历史误差一直累加 × KI。
//                专门消除"稳态误差"——比如目标 200、实际总差 20 上不去，
//                久了积分项慢慢攒大，就能把这 20 补上。**看过去**。
//   D（微分）  ：误差的"变化速度" × KD。
//                误差开始快速缩小时提前收力，防止冲过头来回振荡。**看未来趋势**。
//
//   调参口诀（工业界通用，先 P 后 I 最后 D）：
//     ① 先把 KI、KD 清零，只加 KP，加到轮子能稳稳跟住目标
//     ② KP 大了会"嗡——嗡——"来回振荡，就退回去一点
//     ③ 速度总差一点点到不了目标 → 加 KI（从小往大加，太大了会周期性摆）
//     ④ 最后加一点 KD 压掉振荡
//     **注意**：本设计里 KP/KI/KD 的单位是"每 5ms 一次控制"，
//               而经典 PID 的 KP/KI/KD 隐含"每秒"。两者差 200 倍，
//               所以你从网上抄来的参数不能直接用，必须自己调。
//
//=============================================================================
// 【为什么参数是整数？—— 定点数，这里是重点】
//
// FPGA 里没有"浮点数"这种便宜东西（真要用浮点得占一大片硬件资源），
// 所以下面用【定点数】—— 用一个整数 + 一个隐含的小数点位置来表示小数。
//
//   本模块约定：**所有参数的最低位表示 1/128**，即 PARAM_SHIFT = 7。
//
//     你填 KP = 256  → 等效于 256/128 = 2.000
//     你填 KP = 128  → 等效于 128/128 = 1.000
//     你填 KP = 64   → 等效于  64/128 = 0.500
//     你填 KP = 1    → 等效于   1/128 = 0.0078（最小步进）
//
//   为什么选 7 位小数（1/128）？
//     太小（如 1/4096）→ 想调到 2.0 要填 8192，按键按到手酸
//     太大（如 1/16）  → 只有 0.0625 的步进，细微差别调不出来
//     1/128 = 0.0078 是个好折中：按键每按一下走 0.008，20 下走 0.16
//
//   但按键调参时不应该让你面对 256 这种数字，所以**按键步长另定**：
//   顶层的做法是每按一下 KP 加 8（= 0.0625），这样按 16 下正好从 1.0 到 2.0，
//   数字既细腻又好数。串口会把 KP 换算成小数打印出来（256 → "2.000"）。
//
//=============================================================================
// 【PID 输出公式】整数算，没有浮点
//
//   err    = target - actual                  （补码，可正可负）
//   P_term = err    × KP
//   D_term = d_err  × KD     （d_err = 本次误差 - 上次误差）
//   I_term = I_acc  × KI     （I_acc 是"每控制周期累加一次误差"）
//
//   raw    = P_term + I_term + D_term          （定点，低 7 位是小数）
//   duty   = raw >>> PARAM_SHIFT               （右移 7 位 = ÷128，还原成"千分比"）
//
//   >>> 是"算术右移"：负数右移仍保持负数。这点很关键，
//       若用逻辑右移，负的 duty 会变成一个巨大的正数 → 电机猛地反转。
//=============================================================================
module motor_pid #(
    parameter integer PARAM_SHIFT = 7,    // 参数最低位 = 1/128
    parameter signed [15:0] DUTY_MAX_S = 16'sd1000,   // 输出上限（‰，与驱动满量程一致）
    parameter signed [15:0] DUTY_MIN_S = -16'sd1000,
    // ★V2.9（2026-10-15）★ 段间"短停"不许清积分
    //   背景：绕障斜行/回线是"一串 40mm 小段"，段与段之间 motor_driver_top 的状态机
    //         要过 S_EXT_WAIT/S_IDLE（约 2~3 拍），那几拍 pid_run=0。
    //   旧写法 `!run ⇒ i_acc<=0` 会把每个小段都变成"积分从 0 重新起步"——
    //         稳态时维持速度的占空比几乎全靠积分（P 项在 err≈0 时≈0），
    //         于是占空比瞬间掉到近 0、要 ~100~200ms 才爬回来 ⇒ 现场 ≈3Hz 的"一顿一顿"。
    //   新写法：run 掉下来只计时，连续 IDLE_CLR_MS 都不在跑才算"真停"
    //         （急停 / 顶住障碍 / 任务跑完 ⇒ 照旧清积分，安全行为不变）；
    //         段间空档（µs 级）则把积分原样留着 ⇒ 下一小段一装上就是满血。
    parameter integer CLK_FREQ_HZ = 50_000_000,
    parameter integer IDLE_CLR_MS = 50
)(
    input  wire                clk,
    input  wire                rst_n,
    // ---- 控制指令 ----
    input  wire                run,            // 1 = 允许闭环输出；0 = 指令恒为 0（停）
    input  wire                i_clr,          // 1 = 清积分（段切换时脉冲，防止跨段拖尾）
    input  wire signed [15:0]  target,         // 目标速度（补码）
    input  wire signed [15:0]  actual,         // 实测速度（来自 encoder_decode）
    input  wire                actual_strobe,  // 测速更新脉冲：每个脉冲只算一次 PID
    // ---- 参数（可以在线改，下一拍即生效）----
    input  wire [15:0]         kp,             // 定点：实际值 = kp / 128
    input  wire [15:0]         ki,
    input  wire [15:0]         kd,
    // ---- 输出 ----
    output reg  signed [15:0]  duty,           // 送给 tb6612_driver 的占空比指令
    // ---- 给串口/LED 看的中间量（不参与控制，纯观测）----
    output wire signed [15:0]  err_out,
    output wire signed [15:0]  p_term_out
);

    // =========================================================================
    // 声明集中放开头（ModelSim 不允许"先用后声明"）
    // =========================================================================
    reg  signed [15:0] target_d;     // 打一拍的目标值
    reg  signed [15:0] err;          // 本次误差
    reg  signed [15:0] err_last;     // 上次误差
    reg  signed [15:0] d_err;        // 误差的变化量

    reg  signed [15:0] i_acc;        // 积分累加器（和误差同宽，符号最干净）
    reg  signed [15:0] i_sum;        // 中间和（先算出来，再单独钳位）

    reg  signed [31:0] p_term;       // P 项（定点，放大 128 倍）
    reg  signed [31:0] i_term;       // I 项（定点）
    reg  signed [31:0] d_term;       // D 项（定点）
    reg  signed [31:0] raw;          // 三项之和（定点）
    reg  signed [31:0] raw_lim;      // 限幅后、右移前的值

    // 积分累加器上限。
    // 【为什么定这个数】积分项的最终贡献 = i_acc × KI ÷ 128。
    //   要让它最大能推出满量程（1000‰），i_acc 就得到 1000×128/KI 量级。
    //   取 ±20000 时，即使 KI 只有 0.5（=64），i_acc 也能贡献 20000×64/128 = 10000‰，
    //   远超满量程 —— 够用，同时又不至于把 16 位塞满（32767）。
    //   注意：这正是"抗积分饱和"该管的事，本版按用户要求只做这层基础钳位。
    localparam signed [15:0] I_ACC_MAX = 16'sd20000;
    localparam signed [15:0] I_ACC_MIN = -16'sd20000;
    // 积分项输出限幅 = 输出上限的 40%（1000‰ × 0.4 = 400‰）
    // ⚠️ 2026-09-28 改：提速度后这个 400‰ 变成了"速度天花板" ——
    //   稳态时 P 项≈0，维持速度的占空比全靠积分顶：
    //     需要占空比 ≈ 死区(~150‰) + 速度/2.35
    //     目标 400counts/5ms → ~320‰（够）；600 → ~405‰（顶住）；800 → ~490‰（够不到）
    //   仿真（sim/tb_speed.v）实测：限 400‰ 时目标 800 只能跑到 199mm/s。
    //   这里放到 700‰（对应约 1500counts/5ms ≈ 520mm/s 的稳态需求），留足余量。
    localparam signed [31:0] I_TERM_LIM = 32'sd115200;   // 900‰ << 7（1.5×速后抬高积分天花板）

    // ★V2.9★：连续多久没在跑才算"真停"（到了才清积分；段间空档不会到）
    //   50ms @50MHz = 2,500,000 拍 ⇒ 24 位够（1.6e7）
    localparam [23:0] IDLE_CLR_CYC = (CLK_FREQ_HZ / 1000) * IDLE_CLR_MS;
    reg [23:0] idle_cnt;

    // =========================================================================
    // 1) 误差 + 微分项
    //    target 是上层给的，和 actual 不同源；把 target 打一拍再用，
    //    避免同一拍里 target 刚变、actual 却是旧的，导致 err 出现瞬时尖峰。
    // =========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            target_d <= 16'sd0;
            err      <= 16'sd0;
            err_last <= 16'sd0;
            d_err    <= 16'sd0;
        end
        else begin
            target_d <= target;
            err      <= target_d - actual;    // 误差 = 目标 - 实际
            err_last <= err;
            d_err    <= err - err_last;       // 误差这次变了多少
        end
    end

    // =========================================================================
    // 2) 积分累加器
    //    只在 actual_strobe 那一拍累加 —— 每个测速周期（5ms）累加一次。
    //    如果每拍都累加，积分速度就跟 50MHz 时钟绑死，KI 会完全没法调。
    //    **积分周期必须等于控制周期**，这是硬要求。
    //
    //    ⚠️ 踩过的坑（2026-09-20，仿真里抓到）：
    //       起初把"相加"和"钳位判断"写在一个表达式里：
    //           if (i_acc + {{...}, err} > I_ACC_MAX) i_acc <= I_ACC_MAX;
    //           else if (i_acc + {{...}, err} < I_ACC_MIN) i_acc <= I_ACC_MIN;
    //           else i_acc <= i_acc + {{...}, err};
    //       仿真里 i_acc 直接卡死在 ±4000000 一动不动，电机速度永远停在一个值。
    //       原因是同一个加法被算了三遍，而且复位后第一拍各信号还不是稳定值，
    //       比较结果就不可靠（综合工具对这种写法也容易推错）。
    //
    //       **正确做法：先算出一个中间和（sum_next），再单独对它做钳位。**
    //       加法只算一次、判断只针对一个已经稳的值 —— 这是写累加器类逻辑的通用套路。
    // =========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            i_acc    <= 16'sd0;
            idle_cnt <= 24'd0;
        end
        else if (i_clr) begin
            // 段切换 / 动作类型变更：照旧立刻清（防止上一段的积分拖尾）
            i_acc    <= 16'sd0;
            idle_cnt <= 24'd0;
        end
        else if (!run) begin
            // ★V2.9★：短停（段间空档，µs 级）保留积分；连续 IDLE_CLR_MS 没跑 ⇒ 认"真停"
            if (idle_cnt >= IDLE_CLR_CYC)
                i_acc <= 16'sd0;               // 真停够久了 ⇒ 清（原行为）
            else
                idle_cnt <= idle_cnt + 24'd1;  // 还没到 ⇒ 积分原样留着
        end
        else begin
            idle_cnt <= 24'd0;
            if (actual_strobe) begin
                i_sum = i_acc + err;           // 步骤一：先算出和
                if (i_sum > I_ACC_MAX)         // 步骤二：再对"算好的和"钳位
                    i_acc <= I_ACC_MAX;
                else if (i_sum < I_ACC_MIN)
                    i_acc <= I_ACC_MIN;
                else
                    i_acc <= i_sum;
            end
        end
    end

    // =========================================================================
    // 3) 三项相乘（用片上 DSP 硬核乘法器，不占逻辑资源）
    //    参数是 16 位无符号（KP/KI/KD 不会是负的），所以用一个 0 在高位补成
    //    17 位有符号，这样两个有符号数相乘的语义最明确。
    // =========================================================================
    reg signed [31:0] i_mul;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            p_term <= 32'sd0;
            i_term <= 32'sd0;
            d_term <= 32'sd0;
            i_mul  <= 32'sd0;
        end
        else begin
            p_term <= err * $signed({1'b0, kp});
            i_mul  <= i_acc * $signed({1'b0, ki});
            // 积分限幅：|I| ≤ 输出上限的 40%（400‰）
            if (i_mul > I_TERM_LIM)
                i_term <= I_TERM_LIM;
            else if (i_mul < -I_TERM_LIM)
                i_term <= -I_TERM_LIM;
            else
                i_term <= i_mul;
            d_term <= d_err * $signed({1'b0, kd});
        end
    end

    // =========================================================================
    // 4) 求和 + 限幅
    //    限幅要在"右移之前"做，且限幅的阈值也要同样放大 128 倍（<<< 7）。
    // =========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            raw     <= 32'sd0;
            raw_lim <= 32'sd0;
        end
        else begin
            raw <= p_term + i_term + d_term;

            if (raw > (DUTY_MAX_S <<< PARAM_SHIFT))
                raw_lim <= DUTY_MAX_S <<< PARAM_SHIFT;
            else if (raw < (DUTY_MIN_S <<< PARAM_SHIFT))
                raw_lim <= DUTY_MIN_S <<< PARAM_SHIFT;
            else
                raw_lim <= raw;
        end
    end

    // =========================================================================
    // 5) 还原成占空比：右移 PARAM_SHIFT 位 = ÷128
    // =========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            duty <= 16'sd0;
        else if (!run)
            duty <= 16'sd0;                        // 不允许跑 → 指令直接归 0
        else
            duty <= raw_lim[15+PARAM_SHIFT:PARAM_SHIFT]; // 显式取 16 位，避免位宽截断警告
    end

    // 给串口观测用（纯读出，不影响控制）
    assign err_out    = err;
    assign p_term_out = p_term[31:16];

endmodule
